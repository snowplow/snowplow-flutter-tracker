import 'package:flutter/foundation.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:snowplow_tracker/snowplow_tracker.dart';

import 'helpers.dart';

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  final List<InspectableEvent> events = [];
  SnowplowTracker? tracker;

  Future<InspectableEvent> waitForEvent(
      bool Function(InspectableEvent event) matches) async {
    for (int i = 0; i < 50; i++) {
      for (final event in events) {
        if (matches(event)) {
          return event;
        }
      }
      await Future.delayed(const Duration(milliseconds: 100));
    }
    throw StateError('No matching event in ${events.map(_describe).toList()}');
  }

  setUpAll(() async {
    tracker = await Snowplow.createTracker(
        namespace: 'plugin',
        endpoint: SnowplowTests.microEndpoint,
        plugins: [
          PluginConfiguration(
              identifier: 'recorder',
              afterTrack: (event) {
                // ignore: avoid_print
                print('afterTrack: ${_describe(event)}');
                events.add(event);
              }),
          PluginConfiguration(
              identifier: 'guest', entities: [_guest('initial')])
        ]);
  });

  setUp(() {
    events.clear();
  });

  testWidgets('calls afterTrack for structured events',
      (WidgetTester tester) async {
    await tracker
        ?.track(const Structured(category: 'category', action: 'action'));

    final event = await waitForEvent((e) => e.name == 'se');
    expect(event.schema, isNull);
    expect(event.payload['se_ca'], equals('category'));
    expect(event.payload['se_ac'], equals('action'));
  });

  testWidgets('calls afterTrack for self-describing events with entities',
      (WidgetTester tester) async {
    await tracker?.track(
        const SelfDescribing(
            schema:
                'iglu:com.snowplowanalytics.snowplow/link_click/jsonschema/1-0-1',
            data: {'targetUrl': 'http://a-target-url.com'}),
        contexts: [
          const SelfDescribing(
              schema: 'iglu:org.schema/WebPage/jsonschema/1-0-0',
              data: {
                'keywords': ['tester']
              })
        ]);

    final event = await waitForEvent((e) =>
        e.schema ==
        'iglu:com.snowplowanalytics.snowplow/link_click/jsonschema/1-0-1');
    expect(event.payload['targetUrl'], equals('http://a-target-url.com'));
    final webPage = event.entities.firstWhere((entity) =>
        entity.schema == 'iglu:org.schema/WebPage/jsonschema/1-0-0');
    expect(webPage.data['keywords'], equals(['tester']));
  });

  testWidgets('calls afterTrack for events generated by the native tracker',
      (WidgetTester tester) async {
    await tracker?.track(const ScreenView(name: 'first'));
    await tracker?.track(const ScreenView(name: 'second'));

    await waitForEvent((e) =>
        e.schema?.contains('/screen_view/') == true &&
        e.payload['name'] == 'second');
    // screen_end is tracked natively before the second screen view
    final screenEnd =
        await waitForEvent((e) => e.schema?.contains('/screen_end/') == true);
    expect(screenEnd.entities.map((e) => e.schema),
        contains(contains('/screen/')));
  }, skip: kIsWeb);

  testWidgets('stops calling afterTrack after the plugin is removed',
      (WidgetTester tester) async {
    await tracker?.removePlugin('recorder');
    await tracker
        ?.track(const Structured(category: 'removed', action: 'action'));
    await Future.delayed(const Duration(seconds: 2));

    expect(events.where((e) => e.payload['se_ca'] == 'removed'), isEmpty);

    await tracker?.addPlugin(
        PluginConfiguration(identifier: 'recorder', afterTrack: events.add));
    await tracker?.track(const Structured(category: 'readded', action: 'a'));
    await waitForEvent((e) => e.payload['se_ca'] == 'readded');
  });

  testWidgets('adds plugin entities to events', (WidgetTester tester) async {
    await tracker?.track(const Structured(category: 'initial', action: 'a'));

    final event = await waitForEvent((e) => e.payload['se_ca'] == 'initial');
    expect(_guests(event), equals(['initial']));
  });

  testWidgets('adds the entities set by setPluginEntities',
      (WidgetTester tester) async {
    await tracker?.setPluginEntities('guest', [_guest('updated')]);
    await tracker?.track(const Structured(category: 'updated', action: 'a'));

    final event = await waitForEvent((e) => e.payload['se_ca'] == 'updated');
    expect(_guests(event), equals(['updated']));
  });

  testWidgets('keeps the previous entities for events tracked before the swap',
      (WidgetTester tester) async {
    await tracker?.setPluginEntities('guest', [_guest('before')]);
    // Not awaited, so the swap follows while the tracker is still
    // processing these events.
    final tracked = [
      for (var i = 0; i < 20; i++)
        tracker?.track(
            Structured(category: 'before-swap', action: 'a', label: '$i'))
    ];
    await tracker?.setPluginEntities('guest', [_guest('after')]);
    await Future.wait(tracked.whereType<Future<void>>());
    await tracker?.track(const Structured(category: 'after-swap', action: 'a'));

    await waitForEvent((e) => e.payload['se_ca'] == 'after-swap');
    // afterTrack isn't called in the order the events were tracked on Android
    for (var i = 0; i < 20; i++) {
      await waitForEvent((e) =>
          e.payload['se_ca'] == 'before-swap' && e.payload['se_la'] == '$i');
    }
    final before = events.where((e) => e.payload['se_ca'] == 'before-swap');
    expect(before, hasLength(20));
    for (final event in before) {
      expect(_guests(event), equals(['before']),
          reason: 'event ${event.payload['se_la']}');
    }
    final after = events.firstWhere((e) => e.payload['se_ca'] == 'after-swap');
    expect(_guests(after), equals(['after']));
  });

  testWidgets('adds plugin entities to events generated by the native tracker',
      (WidgetTester tester) async {
    await tracker?.setPluginEntities('guest', [_guest('native')]);
    await tracker?.track(const ScreenView(name: 'third'));
    await tracker?.track(const ScreenView(name: 'fourth'));

    final screenEnd = await waitForEvent((e) =>
        e.schema?.contains('/screen_end/') == true &&
        _guests(e).contains('native'));
    expect(_guests(screenEnd), equals(['native']));
  }, skip: kIsWeb);

  testWidgets('stops adding plugin entities after the plugin is removed',
      (WidgetTester tester) async {
    await tracker?.removePlugin('guest');
    await tracker?.setPluginEntities('guest', [_guest('ignored')]);
    await tracker?.track(const Structured(category: 'no-guest', action: 'a'));

    final event = await waitForEvent((e) => e.payload['se_ca'] == 'no-guest');
    expect(_guests(event), isEmpty);
  });
}

const _guestSchema =
    'iglu:com.snowplowanalytics.iglu/anything-a/jsonschema/1-0-0';

/// Entity added by the `guest` plugin, using a schema that accepts any data.
SelfDescribing _guest(String id) =>
    SelfDescribing(schema: _guestSchema, data: {'id': id});

List<Object?> _guests(InspectableEvent event) => event.entities
    .where((e) => e.schema == _guestSchema)
    .map((e) => e.data['id'])
    .toList();

String _describe(InspectableEvent event) =>
    '${event.schema ?? event.name} ${event.payload} '
    'entities: ${event.entities.map((e) => e.schema).toList()}';

import 'package:flutter/foundation.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';
import 'package:snowplow_tracker/snowplow_tracker.dart';

import 'helpers.dart';

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  final List<InspectableEvent> events = [];
  SnowplowTracker? tracker;

  Future<InspectableEvent> waitForEvent(
      bool Function(InspectableEvent event) matches) async {
    for (int i = 0; i < 50; i++) {
      for (final event in events) {
        if (matches(event)) {
          return event;
        }
      }
      await Future.delayed(const Duration(milliseconds: 100));
    }
    throw StateError('No matching event in ${events.map(_describe).toList()}');
  }

  setUpAll(() async {
    tracker = await Snowplow.createTracker(
        namespace: 'plugin',
        endpoint: SnowplowTests.microEndpoint,
        plugins: [
          PluginConfiguration(
              identifier: 'recorder',
              afterTrack: (event) {
                // ignore: avoid_print
                print('afterTrack: ${_describe(event)}');
                events.add(event);
              })
        ]);
  });

  setUp(() {
    events.clear();
  });

  testWidgets('calls afterTrack for structured events',
      (WidgetTester tester) async {
    await tracker
        ?.track(const Structured(category: 'category', action: 'action'));

    final event = await waitForEvent((e) => e.name == 'se');
    expect(event.schema, isNull);
    expect(event.payload['se_ca'], equals('category'));
    expect(event.payload['se_ac'], equals('action'));
  });

  testWidgets('calls afterTrack for self-describing events with entities',
      (WidgetTester tester) async {
    await tracker?.track(
        const SelfDescribing(
            schema:
                'iglu:com.snowplowanalytics.snowplow/link_click/jsonschema/1-0-1',
            data: {'targetUrl': 'http://a-target-url.com'}),
        contexts: [
          const SelfDescribing(
              schema: 'iglu:org.schema/WebPage/jsonschema/1-0-0',
              data: {
                'keywords': ['tester']
              })
        ]);

    final event = await waitForEvent((e) =>
        e.schema ==
        'iglu:com.snowplowanalytics.snowplow/link_click/jsonschema/1-0-1');
    expect(event.payload['targetUrl'], equals('http://a-target-url.com'));
    final webPage = event.entities.firstWhere((entity) =>
        entity.schema == 'iglu:org.schema/WebPage/jsonschema/1-0-0');
    expect(webPage.data['keywords'], equals(['tester']));
  });

  testWidgets('calls afterTrack for events generated by the native tracker',
      (WidgetTester tester) async {
    await tracker?.track(const ScreenView(name: 'first'));
    await tracker?.track(const ScreenView(name: 'second'));

    await waitForEvent((e) =>
        e.schema?.contains('/screen_view/') == true &&
        e.payload['name'] == 'second');
    // screen_end is tracked natively before the second screen view
    final screenEnd =
        await waitForEvent((e) => e.schema?.contains('/screen_end/') == true);
    expect(screenEnd.entities.map((e) => e.schema),
        contains(contains('/screen/')));
  }, skip: kIsWeb);

  testWidgets('stops calling afterTrack after the plugin is removed',
      (WidgetTester tester) async {
    await tracker?.removePlugin('recorder');
    await tracker
        ?.track(const Structured(category: 'removed', action: 'action'));
    await Future.delayed(const Duration(seconds: 2));

    expect(events.where((e) => e.payload['se_ca'] == 'removed'), isEmpty);

    await tracker?.addPlugin(
        PluginConfiguration(identifier: 'recorder', afterTrack: events.add));
    await tracker?.track(const Structured(category: 'readded', action: 'a'));
    await waitForEvent((e) => e.payload['se_ca'] == 'readded');
  });
}

String _describe(InspectableEvent event) =>
    '${event.schema ?? event.name} ${event.payload} '
    'entities: ${event.entities.map((e) => e.schema).toList()}';
